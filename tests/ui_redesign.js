// Consumer-shell regression. Uses only the explicit isolated port/store.
// Run through tests/ui_run.mjs; this does not connect to a real Grok Bot.
async (page) => {
  const origin = globalThis.UI_TEST.origin;
  const root = globalThis.UI_TEST.root;
  const passed = [];
  const check = (value, message) => { if (!value) throw new Error(message); };
  const api = async (path, method = "GET", data) => {
    const response = await page.request.fetch(origin + path, { method, ...(data ? { data } : {}) });
    check(response.ok(), method + " " + path + " failed");
    return response.json();
  };
  const health = await api("/health");
  check(health.data_dir.startsWith(root + "/out/redesign-test"), "Wrong isolated data directory.");
  check(!(await api("/api/bots")).bots.length, "Use a fresh isolated test directory.");
  const ready = () => page.waitForFunction(() => document.documentElement.dataset.appReady === "true");
  const clipboard = () => page.evaluate(() => Object.defineProperty(navigator, "clipboard", { configurable: true, value: { writeText: async (text) => { window.__testCopied = text; } } }));
  const frame = async () => {
    await page.waitForFunction(() => { const frame = document.querySelector("#space-frame"); return frame && !frame.hidden && frame.srcdoc.length > 0; });
    const result = await (await page.locator("#space-frame").elementHandle()).contentFrame();
    await result.waitForFunction(() => window.probe?.initial);
    return result;
  };
  await page.goto(origin);
  await page.setViewportSize({ width: 1280, height: 850 });
  await ready();
  await page.locator("#empty-create").click();
  await page.locator("#create-name").fill("独立测试 Bot A");
  await page.locator("#create-submit").click();
  await page.waitForFunction(() => !document.querySelector("#create-dialog").open);
  await page.locator("#empty-create").click();
  await page.locator("#create-name").fill("页面 A");
  await page.locator("#create-submit").click();
  await page.locator("#page-empty").waitFor({ state: "visible" });
  check(await page.locator("#data-view").isHidden(), "Raw data appeared on the main canvas.");
  await clipboard();
  await page.locator("#empty-setup").click();
  await page.waitForFunction(() => window.__testCopied?.includes("grok-space"));
  check(await page.locator("#ai-action").isHidden(), "A separate AI composer appeared.");
  passed.push("Explicit Bot association, page creation, setup copy; no separate AI composer");
  await page.locator("#html-file").setInputFiles(root + "/tests/ui_probe.html");
  let active = await frame();
  await active.locator("#write").click();
  await active.locator("#feedback").filter({ hasText: "Saved through the SDK" }).waitFor();
  const initial = await active.evaluate(() => spaces.get());
  const spaceA = initial.space.id;
  const botA = initial.space.bot_id;
  const instance = await active.evaluate(() => probe.instance);
  await page.locator("#actions-menu > summary").click();
  await page.locator("#advanced-action").click();
  await page.locator("#state-json").waitFor({ state: "visible" });
  check(await page.locator("#state-json").textContent().then((text) => text.includes('"probe": "saved"')), "Saved state missing in advanced view.");
  await page.locator('[data-close="advanced-dialog"]').click();
  check(await active.evaluate(() => probe.instance) === instance, "Advanced dialog rebuilt the page.");
  await page.reload();
  await ready();
  active = await frame();
  check((await active.evaluate(() => spaces.get())).state.probe === "saved", "An SDK edit was lost after reload.");
  passed.push("HTML import, SDK control save, reload persistence, advanced dialog preserves iframe");
  await clipboard();
  await active.evaluate(async () => { const snapshot = await spaces.get(); await spaces.action("request", { instruction: "独立测试请求" }, { expected_revision: snapshot.revision }); });
  await page.waitForFunction(() => document.querySelector("#pending-count").textContent === "1");
  const detailA = await api("/api/spaces/" + spaceA);
  check(detailA.pending_count === 1, "A copied request must remain pending.");
  await page.locator("#save-status").click();
  await page.locator("#activity-view").waitFor({ state: "visible" });
  await page.getByRole("button", { name: "待处理（1）", exact: true }).click();
  await page.locator(".event-status.pending").waitFor();
  await page.locator('[data-close="advanced-dialog"]').click();
  await page.locator("#actions-menu > summary").click();
  await page.locator("#pages-action").click();
  check(await page.locator("#pages-dialog").textContent().then((text) => text.includes("尚未连接")), "Pages must clearly state unavailable.");
  await page.locator("#pages-dialog").getByRole("button", { name: "知道了" }).click();
  await page.locator("#actions-menu > summary").click();
  await page.locator("#connection-action").click();
  await page.locator("#setup-action").click();
  await page.waitForFunction(() => window.__testCopied?.includes("grok-space"));
  await page.locator('[data-close="connection-dialog"]').click();
  passed.push("SDK manual request, pending activity, honest Pages availability, connection dialog");
  const botB = (await api("/api/bots", "POST", { name: "独立测试 Bot B" })).bot;
  const spaceB = (await api("/api/spaces", "POST", { bot_id: botB.id, title: "页面 B" })).space;
  await page.locator("#library-toggle").click();
  await page.locator("#library-search").fill("页面 B");
  await page.locator(".library-item").filter({ hasText: "页面 B" }).click();
  await page.waitForFunction((id) => document.querySelector("#space-select").value === id, spaceB.id);
  check(await page.locator("#page-empty").isVisible(), "Empty second page did not render.");
  await page.locator("#library-toggle").click();
  await page.locator("#library-search").fill("页面 A");
  await page.locator(".library-item").filter({ hasText: "页面 A" }).click();
  await page.waitForFunction((id) => document.querySelector("#space-select").value === id, spaceA);
  active = await frame();
  check((await active.evaluate(() => spaces.get())).state.probe === "saved", "Switching Bots lost or mixed saved state.");
  check((await api("/api/spaces/" + spaceB.id)).state.probe === undefined, "Bot A data leaked into Bot B.");
  passed.push("Library search, cross-Bot selection, isolation, return to saved canvas");
  for (const width of [320, 420, 520, 1280]) {
    await page.setViewportSize({ width, height: 850 });
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Canvas overflow at " + width);
    await page.locator("#library-toggle").click();
    check(await page.evaluate(() => { const rect = document.querySelector("#library-dialog").getBoundingClientRect(); return rect.left >= 0 && rect.right <= innerWidth; }), "Library overflow at " + width);
    await page.locator('[data-close="library-dialog"]').click();
    if (width === 520) await page.screenshot({ path: root + "/output/playwright/redesign-host-520.png", scale: "css" });
  }
  passed.push("320, 420, 520, 1280 canvas and library fit without horizontal overflow");
  return { passed, spaceA, botA, boundary: "Isolated Chromium/local HTTP. Clipboard stubbed. No real Bot, native window mode or OS visibility acceptance." };
}
